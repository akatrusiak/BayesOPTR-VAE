"""
For one trained surrogate (seed s, N training runs) and one or more VAE
checkpoints sharing that same (seed, N, val_frac), measure whether the
VAE's decoded ẑ produces landscape predictions that are meaningfully
better than a VAE-free baseline.

The question this script answers
--------------------------------
Is the latent z generated by the VAE's encoder actually informative about
the run's landscape, OR is decode(ẑ) indistinguishable from the training
distribution mean δ̄?  The surrogate ĝ(x, δ) ≈ y is our cheap stand-in for
TRANSOPTR — it lets us compute landscape-fidelity metrics without
re-simulating.  Because the surrogate has systematic bias (R² ≈ 0.35), we
compare *paired differences* across δ choices on the same runs, which
cancels any δ-independent surrogate error.

The four δ choices evaluated per val run
----------------------------------------
  true     δ = δ_true            oracle upper bound — the surrogate's
                                 best possible landscape given the run
  decoded  δ = decode(μ_φ)       what the VAE actually produces
  mean     δ = δ̄_train           training-mean baseline = decode(z=0)
                                 under the VAE's KL regularization;
                                 this is the "no VAE" reference
                                 in Stage 4 of the proposal
  zero     δ = 0 (physical)      perfectly aligned machine, secondary
                                 completeness check

Layered interpretation
----------------------
Layer 0 — surrogate sanity.  Does MSE(true) < MSE(mean) on val runs?
  If no, the surrogate is not responsive to δ at all and the downstream
  comparison is meaningless.  Hard-fail early if so.

Layer 1 — VAE signal.  Does MSE(decoded) < MSE(mean) on val runs?
  Paired Wilcoxon signed-rank across runs.  A statistically significant
  negative difference is evidence the VAE's latent carries real
  landscape-relevant information.

Alignment requirements
----------------------
Surrogate and VAE must share the training seed, val_frac, and (implicitly)
the same MultiFolderRunDataset ordering — otherwise their val splits
differ and the paired comparison is invalid.  This is asserted.

Outputs
-------
  <out_dir>/per_checkpoint_<d_z>.json  per-VAE-checkpoint full results
  <out_dir>/summary.json               aggregate across all checkpoints
"""
